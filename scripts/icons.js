import { promises as fs } from 'fs';
import path from 'path';
import os from 'os';
import { FontAssetType, generateFonts } from 'fantasticon';

const INPUT_DIR = 'style/icons';
const OUTPUT_SCSS = 'style/icons.scss';
const FONT_NAME = 'lil-gui';

const template = data => `// generated by scripts/icons.js
@font-face { 
	font-family: '${FONT_NAME}';
	src: url('data:application/font-woff2;charset=utf-8;base64,${data}') format('woff2');
}`;

const getIconId = ( { basename } ) => `icon-${basename}`;

const codepoints = {};
const files = await fs.readdir( INPUT_DIR );

// get codepoints from the file names (uXXXX-icon-name)
for ( const file of files ) {
	const basename = path.basename( file, '.svg' );
	const codepoint = parseInt( basename.substring( 1, 5 ), 16 );
	const iconId = getIconId( { basename } );
	codepoints[ iconId ] = codepoint;
}

// write font to a temp directory, then delete it after we're done
const tmpPrefix = path.join( os.tmpdir(), 'lil-gui-icons-' );
const outputDir = await fs.mkdtemp( tmpPrefix );

let results;
try {
	results = await generateFonts( {
		inputDir: INPUT_DIR,
		name: FONT_NAME,
		fontTypes: [ FontAssetType.WOFF2 ],
		assetTypes: [],
		codepoints,
		getIconId,
		outputDir
	} );
} finally {
	await fs.rm( outputDir, { recursive: true, force: true } );
}

// get font data as a base64 string
const data = results.assetsOut[ FontAssetType.WOFF2 ].toString( 'base64' );

await fs.writeFile( OUTPUT_SCSS, template( data ) );

const K = ( await fs.stat( OUTPUT_SCSS ) ).size / 1000;
console.log( `${INPUT_DIR}/*.svg → ${OUTPUT_SCSS} [${K.toFixed( 2 )}K]` );

